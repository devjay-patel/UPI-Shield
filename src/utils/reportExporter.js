/**
 * Incident Report Exporter
 * Generates an official summary text report ready to submit to cybercrime.gov.in
 * or read over the phone to the 1930 Cyber Crime Helpline.
 * 100% In-Browser. No data sent to any server.
 */

import { detectAndMaskSecrets } from '../engine/fraudEngine.js';

export function generateIncidentReport(analysis, paymentData) {
  const timestamp = new Date().toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' });
  // Never write real-looking PINs/OTPs/card numbers into the file
  const safe = (v) => detectAndMaskSecrets(v || '').maskedText;

  const signalsText = (analysis?.signals || [])
    .map((s, idx) => `  ${idx + 1}. [${s.group}] ${s.label} (+${s.points} pts)\n     Evidence: "${safe(s.evidence)}"\n     Details: ${s.explanation}`)
    .join('\n\n');

  const reportText = `=====================================================
NATIONAL CYBER CRIME HELPLINE (1930) - INCIDENT BRIEF
Generated by UPI Shield (Team ThreatZero)
Date & Time: ${timestamp} IST
=====================================================

1. SUSPECT TRANSACTION DETAILS:
-----------------------------------------------------
- Payee Name      : ${paymentData.recipientName || 'Not Specified'}
- Suspect UPI VPA : ${paymentData.upiId || 'Not Specified'}
- Amount Involved : ₹${paymentData.amount || '0'}
- Request Type    : ${(paymentData.type || 'pay').toUpperCase()} Request
- Note / Message  : ${safe(paymentData.message || paymentData.qrDescription) || 'None'}
- Attached Link   : ${safe(paymentData.link) || 'None'}

2. FRAUD ENGINE RISK ASSESSMENT:
-----------------------------------------------------
- Calculated Risk Score : ${analysis?.riskScore || 0} / 100
- Indicated Risk Level  : ${analysis?.riskLevel || 'UNKNOWN'}
- Primary Action Flag   : ${analysis?.mainAction || 'None'}

3. DETECTED FRAUD SIGNALS & EVIDENCE:
-----------------------------------------------------
${signalsText || '  None detected.'}

4. USER ACTIONS RECOMMENDED:
-----------------------------------------------------
- Do NOT share your UPI PIN or OTP with anyone.
- Immediately notify your bank's fraud desk to freeze any uncommitted transactions.
- File this report at the National Cyber Crime Portal: https://cybercrime.gov.in
- Call the toll-free National Cyber Crime Helpline at 1930.

=====================================================
DISCLAIMER: This report is generated by UPI Shield for
investigative aid. Analysis runs entirely on the client
device and does not constitute a legal certification.
=====================================================`;

  // Trigger local in-browser file download
  const blob = new Blob([reportText], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `UPI_Shield_Incident_Report_${Date.now()}.txt`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
